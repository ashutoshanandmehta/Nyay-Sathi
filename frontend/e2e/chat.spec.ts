test('unrelated questions preserve case memory across refresh',async({page})=>{
  await page.goto('/')
  const box=page.getByRole('textbox',{name:'Message',exact:true});await expect(box).toBeEnabled()
  await box.fill('My defective phone cost ₹18,000')
  await page.getByRole('button',{name:'Send message',exact:true}).click()
  await expect(page.getByText('AI configuration required:',{exact:true})).toBeVisible()
  const cid=new URL(page.url()).pathname.split('/').at(-1)
  const before=await (await page.request.get(`/api/conversations/${cid}`)).json()
  await expect(page.getByRole('button',{name:'Send message',exact:true})).toBeDisabled()
  await box.fill('When did Jio release its IPO?')
  await page.getByRole('button',{name:'Send message',exact:true}).click()
  await expect(box).toHaveValue('')
  await expect(page.getByRole('main').getByText(/Your message is saved in this chat/)).toBeVisible()
  await page.reload()
  await expect(page.getByText('When did Jio release its IPO?',{exact:true})).toBeVisible()
  const after=await (await page.request.get(`/api/conversations/${cid}`)).json()
  expect(after.case_memory).toEqual(before.case_memory)
  expect(after.messages.at(-1).metadata.task_plan[0].workflow).toBe('general')
})
